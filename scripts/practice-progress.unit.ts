import assert from 'node:assert/strict';
import { PracticeStore, PRACTICE_KEY } from '../src/practice/progress';
import { PRACTICE_LESSONS } from '../server/practice/definitions';
const values = new Map<string, string>();
const storage = { getItem: (key: string) => values.get(key) ?? null, setItem: (key: string, value: string) => { values.set(key, value); } };
let store = new PracticeStore(storage);
assert(store.shouldOffer); store.skipOffer(); assert.equal(store.value.status, 'skipped');
store = new PracticeStore(storage); assert(!store.shouldOffer); assert.equal(store.value.status, 'skipped');
assert.equal(store.value.lessons.basics, 'not-started');
store.mark('basics', 'skipped'); assert.equal(new PracticeStore(storage).value.lessons.basics, 'skipped');
store.mark('weapon', 'completed'); store.mark('weapon', 'skipped'); assert.equal(store.value.lessons.weapon, 'completed');
for (const id of PRACTICE_LESSONS) store.mark(id, 'completed');
assert.equal(new PracticeStore(storage).value.status, 'completed');
values.clear(); values.set('ascend.practice.v1', JSON.stringify({ version: 1, offered: true, status: 'completed', lessons: { basics: 'completed', weapon: 'completed', blackhole: 'completed', defense: 'completed' } }));
store = new PracticeStore(storage);
assert.equal(store.value.version, 2); assert.equal(store.value.lessons.basics, 'completed');
assert.equal(store.value.lessons.weapon, 'completed'); assert.equal(store.value.lessons.blackhole, 'completed');
assert.equal(store.value.lessons.combat, 'not-started'); assert.equal(store.value.lessons.defense, 'not-started');
assert(store.value.legacyCompleted.defense); assert.equal(store.value.status, 'in-progress'); assert(!store.shouldOffer);
assert(values.has('ascend.practice.v1'), 'migration preserves the original record');
assert(new PracticeStore(storage).value.legacyCompleted.defense, 'historical achievement persists after migration');
store.mark('defense', 'skipped'); assert.notEqual(store.value.lessons.defense, 'completed');
store.mark('defense', 'completed'); assert.equal(store.value.lessons.defense, 'completed');
values.clear(); values.set('ascend.guideSeen', 'true'); store = new PracticeStore(storage);
assert(!store.shouldOffer); assert.equal(store.value.lessons.basics, 'not-started');
values.clear(); values.set(PRACTICE_KEY, '{bad JSON'); assert(new PracticeStore(storage).shouldOffer);
values.set(PRACTICE_KEY, JSON.stringify({version:2,lessons:{basics:'cheated'},offered:'yes'}));
assert.equal(new PracticeStore(storage).value.lessons.basics,'not-started');
store = new PracticeStore({getItem(){throw Error('blocked')},setItem(){throw Error('blocked')}});
store.mark('defense','completed'); assert.equal(store.value.lessons.defense,'completed'); assert(!store.shouldOffer);
console.log('Practice progress v2: five lessons, honest mastery migration with historical defense retained, skipped/complete replay, blocked storage and first-visit behavior pass.');
