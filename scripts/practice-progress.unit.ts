import assert from 'node:assert/strict';
import { PracticeStore, PRACTICE_KEY } from '../src/practice/progress';
const values = new Map<string, string>();
const storage = { getItem: (key: string) => values.get(key) ?? null, setItem: (key: string, value: string) => { values.set(key, value); } };
let store = new PracticeStore(storage);
assert(store.shouldOffer); store.skipOffer(); assert.equal(store.value.status, 'skipped');
store = new PracticeStore(storage); assert(!store.shouldOffer); assert.equal(store.value.lessons.basics, 'not-started');
store.mark('basics', 'skipped'); assert.equal(new PracticeStore(storage).value.lessons.basics, 'skipped');
store.mark('weapon', 'completed'); store.mark('weapon', 'skipped'); assert.equal(store.value.lessons.weapon, 'completed');
for (const id of ['basics', 'blackhole', 'defense'] as const) store.mark(id, 'completed');
assert.equal(new PracticeStore(storage).value.status, 'completed');
values.clear(); values.set('ascend.guideSeen', 'true'); store = new PracticeStore(storage);
assert(!store.shouldOffer); assert.equal(store.value.lessons.basics, 'not-started', 'old guide does not certify new skills');
values.clear(); values.set(PRACTICE_KEY, '{bad JSON'); assert(new PracticeStore(storage).shouldOffer);
values.set(PRACTICE_KEY, JSON.stringify({version:1,lessons:{basics:'cheated'},offered:'yes'}));
assert.equal(new PracticeStore(storage).value.lessons.basics,'not-started');
store = new PracticeStore({getItem(){throw Error('blocked')},setItem(){throw Error('blocked')}});
store.mark('defense','completed'); assert.equal(store.value.lessons.defense,'completed'); assert(!store.shouldOffer);
console.log('Practice progress: version validation, skip/unfinished/completion, replay preservation, old-guide migration and blocked-storage memory fallback passed.');
