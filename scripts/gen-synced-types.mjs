/**
 * Generates src/types/synced.ts: the shapes of the game state the server syncs to browsers, read
 * from the schema field registrations (type(...)(Class.prototype, "field")) in server/schema/, so the
 * client is typed against exactly what arrives, never the server-only fields. Run npm run gen:types
 * after changing a schema; with --check it only fails if the file is out of date (CI runs that).
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const schemaDir = join(root, 'server', 'schema');
const out = join(root, 'src', 'types', 'synced.ts');

const PRIMITIVES = {
  number: 'number', string: 'string', boolean: 'boolean',
  int8: 'number', uint8: 'number', int16: 'number', uint16: 'number', int32: 'number', uint32: 'number',
  int64: 'number', uint64: 'number', float32: 'number', float64: 'number',
};
const nameOf = (cls) => 'Synced' + cls.replace(/Schema$/, '');

function tsType(expr) {
  const e = expr.trim();
  let m;
  if ((m = e.match(/^"(\w+)"$/))) {
    if (!PRIMITIVES[m[1]]) throw new Error(`unknown schema primitive: ${e}`);
    return PRIMITIVES[m[1]];
  }
  if ((m = e.match(/^\[\s*(.+?)\s*\]$/))) return `SyncedArray<${tsType(m[1])}>`;
  if ((m = e.match(/^\{\s*map:\s*(.+?)\s*\}$/))) return `SyncedMap<${tsType(m[1])}>`;
  if ((m = e.match(/^(\w+)$/))) return nameOf(m[1]);
  throw new Error(`unknown schema type: ${e}`);
}

const classes = new Map();
for (const file of readdirSync(schemaDir).filter((f) => f.endsWith('.ts')).sort()) {
  const text = readFileSync(join(schemaDir, file), 'utf8');
  for (const [, expr, cls, field] of text.matchAll(/^type\((.+?)\)\((\w+)\.prototype,\s*"(\w+)"\);/gm)) {
    if (!classes.has(cls)) classes.set(cls, []);
    classes.get(cls).push([field, tsType(expr)]);
  }
}
if (!classes.size) throw new Error('no synced schema fields found');

const lines = [
  '// Generated by scripts/gen-synced-types.mjs from the fields the server syncs (server/schema).',
  "// Don't edit by hand: change the schema, then run npm run gen:types.",
  '',
  '/** A synced map (Colyseus MapSchema), as the browser reads it */',
  'export interface SyncedMap<T> {',
  '    get(key: string): T | undefined',
  '    has(key: string): boolean',
  '    forEach(callback: (value: T, key: string) => void): void',
  '    keys(): IterableIterator<string>',
  '    values(): IterableIterator<T>',
  '    readonly size: number',
  '}',
  '',
  '/** A synced list (Colyseus ArraySchema), as the browser reads it */',
  'export type SyncedArray<T> = ReadonlyArray<T>',
];
for (const [cls, fields] of [...classes].sort((a, b) => nameOf(a[0]).localeCompare(nameOf(b[0])))) {
  lines.push('', `/** ${cls}, as synced to the browser */`, `export interface ${nameOf(cls)} {`);
  for (const [field, type] of fields) lines.push(`    ${field}: ${type}`);
  lines.push('}');
}
const text = lines.join('\n') + '\n';

if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (current.replace(/\r\n/g, '\n') !== text) {
    console.error('src/types/synced.ts is out of date: run npm run gen:types');
    process.exit(1);
  }
  console.log('synced types are up to date');
} else {
  writeFileSync(out, text);
  console.log(`wrote src/types/synced.ts (${classes.size} synced types)`);
}
